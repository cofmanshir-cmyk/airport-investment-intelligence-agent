"""Command-line chat. Run with: python -m src.cli [--provider gemini] ["first question"]"""

from __future__ import annotations

import argparse
import getpass
import json
import os
import sys

import anthropic
from google.genai import errors as gemini_errors

from . import gemini_agent
from .agent import Agent, AgentError, Answer

HELP = "Commands: /raw shows the last tool results as JSON; /quit exits."

_secret = ""


def _redact(text: object) -> str:
    """Remove the API key from text, in case an error message ever includes it."""
    return str(text).replace(_secret, "[REDACTED]") if _secret else str(text)


def render_evidence(answer: Answer) -> str:
    """Build the evidence section in code, so it never depends on the LLM."""
    lines = ["", "-" * 60, "EVIDENCE (generated by Python, not the LLM)"]
    if not answer.tool_calls:
        lines.append("No tool was called for this answer.")
    for call in answer.tool_calls:
        lines.append(f"Tool: {call.name} {json.dumps(call.tool_input)}")
        if call.is_error:
            lines.append(f"  Rejected input: {call.result['error']}")
            continue
        lines.extend(f"  Source: {source}" for source in call.result.get("sources", []))
        lines.extend(f"  Caveat: {caveat}" for caveat in call.result.get("caveats", []))
    if answer.unverified_numbers:
        lines.append(
            "WARNING: these numbers do not match any tool result, so verify them: "
            + ", ".join(answer.unverified_numbers)
        )
    return "\n".join(lines)


def _api_key(env_name: str, label: str) -> str:
    """Read the key from the environment or a hidden prompt; it is never saved."""
    global _secret
    key = os.environ.get(env_name, "").strip()
    if not key:
        if not sys.stdin.isatty():
            raise SystemExit(f"{env_name} is not set.")
        key = getpass.getpass(f"{label} API key (hidden, not saved): ").strip()
    if not key:
        raise SystemExit("No API key entered.")
    _secret = key
    return key


def build_agent(provider: str) -> Agent | gemini_agent.GeminiAgent:
    if provider == "anthropic":
        return Agent(anthropic.Anthropic(api_key=_api_key("ANTHROPIC_API_KEY", "Anthropic")))
    client = gemini_agent.build_client(_api_key("GEMINI_API_KEY", "Gemini"))
    try:
        model = gemini_agent.select_model(client, os.environ.get("GEMINI_MODEL"))
    except AgentError as error:
        raise SystemExit(str(error))
    except gemini_errors.APIError as error:
        raise SystemExit(f"Could not check Gemini models. {_gemini_error(error)}")
    return gemini_agent.GeminiAgent(client, model)


def _gemini_error(error: gemini_errors.APIError) -> str:
    if error.code == 429:
        return "Gemini quota or rate limit reached (429). Wait, or check your limits in Google AI Studio."
    if error.code in (401, 403) or "API_KEY_INVALID" in str(error):
        return "Gemini rejected the API key or its permissions."
    return _redact(f"Gemini API error {error.code}: {error.message}")


def ask_and_print(agent, question: str) -> Answer | None:
    print("\nThinking...", flush=True)
    try:
        answer = agent.ask(question)
    except AgentError as error:
        print(f"\n{error}")
        return None
    except gemini_errors.APIError as error:
        print(f"\n{_gemini_error(error)}")
        return None
    except anthropic.AuthenticationError:
        raise SystemExit("The API key was rejected. Check it and try again.")
    except anthropic.PermissionDeniedError:
        raise SystemExit("This API key cannot use the model.")
    except anthropic.NotFoundError:
        raise SystemExit(f"Model {agent.model!r} was not found. Check ANTHROPIC_MODEL.")
    except anthropic.RateLimitError:
        print("\nRate limited. Wait a moment and try again.")
        return None
    except anthropic.APIStatusError as error:
        print(f"\nAPI error {error.status_code}: {_redact(error.message)}")
        return None
    except anthropic.APIConnectionError:
        print("\nCould not reach the API. Check the network and try again.")
        return None
    print(f"\n{answer.text}")
    print(render_evidence(answer))
    if hasattr(agent, "calls_used"):
        print(f"Gemini calls this session: {agent.calls_used} of {agent.call_limit}")
    return answer


def main() -> None:
    parser = argparse.ArgumentParser(description="Airport Investment Intelligence chat.")
    parser.add_argument("question", nargs="*", help="Optional first question.")
    parser.add_argument(
        "--provider", choices=("anthropic", "gemini"), default=os.environ.get("LLM_PROVIDER", "anthropic"),
    )
    args = parser.parse_args()

    agent = build_agent(args.provider)
    print(f"Airport Investment Intelligence ({agent.model}). {HELP}")
    last = ask_and_print(agent, " ".join(args.question)) if args.question else None
    while True:
        try:
            question = input("\nQuestion> ").strip()
        except (EOFError, KeyboardInterrupt):
            print()
            return
        if not question:
            continue
        if question == "/quit":
            return
        if question == "/raw":
            calls = last.tool_calls if last else []
            print(json.dumps([vars(call) for call in calls], indent=2, default=float) if calls else "No tool results yet.")
            continue
        last = ask_and_print(agent, question) or last


if __name__ == "__main__":
    main()
